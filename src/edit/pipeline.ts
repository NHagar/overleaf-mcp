// The write pipeline (spec §9). Every update, and every edit in a batch, goes through
// prepare (steps 1–6) before anything is sent; then the compile gate, send, post-check,
// and record.

import { BackendError, type EditReceipt, type Splice } from '../adapters/adapter.js';
import { summarizeOp, type AuditLog } from '../audit/log.js';
import { checkCites, checkLabels, checkPreamble } from '../checks/latexchecks.js';
import { generatedInfo } from '../checks/generated.js';
import { Refusal, warning, type Warning } from '../errors.js';
import { describeUnit } from '../model/ids.js';
import { buildProjectOutline, unitAt, type FileOutline, type ProjectOutline, type Unit } from '../model/outline.js';
import type { ProjectSession } from '../session.js';
import { checkBudget, checkReflow, rewrittenUnits } from './budget.js';
import { refineSplice } from './diff.js';
import { applySplices, mapOffset, resolveOps, type Op, type ResolvedSplice } from './ops.js';

export interface UpdateInput {
  file: string;
  ifVersion: number;
  tracked?: boolean;
  rewrite?: boolean;
  allowPreamble?: boolean;
  ops: Op[];
}

interface Prepared {
  input: UpdateInput;
  file: string;
  tracked: boolean;
  baseVersion: number;
  baseText: string;
  newText: string;
  splices: ResolvedSplice[];
  targets: Unit[][];
  warnings: Warning[];
}

export interface OpReceipt {
  op: number;
  units: { id: string; hash: string }[];
  trackedChanges: string[];
}

export interface WriteResult {
  ok: true;
  ver: number;
  files: { file: string; version: number }[];
  receipts: (OpReceipt & { file: string })[];
  warnings: Warning[];
}

/** Options that let `bib add` reuse the pipeline with a pre-built splice. */
export interface RawEdit {
  file: string;
  ifVersion: number;
  tracked?: boolean;
  splices: Splice[];
}

const isBib = (p: string) => p.toLowerCase().endsWith('.bib');

function prepare(session: ProjectSession, input: UpdateInput | (RawEdit & { raw: true }), threshold: number): Prepared {
  // 1. Access
  const doc = session.doc(input.file);
  if (doc.otType !== 'sharejs-text-ot') {
    throw new Refusal('ot_type_unsupported', `${input.file} uses Overleaf's newer "${doc.otType}" document format, which this server can read but not edit yet.`);
  }
  const outline = session.outline;
  const base = outline.files.get(input.file);
  const tracked = input.tracked ?? true;
  if (input.ifVersion > doc.version) {
    throw new Refusal('invalid_op', `ifVersion ${input.ifVersion} is ahead of ${input.file}'s current version ${doc.version}. Use the version from your last read.`);
  }

  // 4. Generated files (checked before resolving so the agent gets the most useful refusal).
  const gen = generatedInfo(doc.text);
  if (gen) {
    throw new Refusal(
      'generated_file',
      `${input.file} is generated by ${gen.script} from ${gen.data}. Don't edit it; tell the user to change the data or the script and rerun ${gen.script}.`,
      gen,
    );
  }

  // 3 + 5. Resolve targets and build the new text.
  let splices: ResolvedSplice[];
  let targets: Unit[][];
  if ('raw' in input) {
    splices = input.splices.map((s) => ({ ...s, opIndex: 0, rewrites: false, move: false }));
    targets = [];
  } else {
    if (!base) throw new Refusal('not_a_doc', `${input.file} is not a LaTeX file the outline covers; use "bib" for .bib files.`);
    const r = resolveOps(outline, input.file, input.ops);
    splices = r.splices;
    targets = r.targets;
  }

  // 2. Freshness: refuse only if a target unit changed since the agent's read.
  if (input.ifVersion < doc.version && base) {
    const changed = session.changedSinceDocVersion(input.file, input.ifVersion);
    const hit = targets.flat().find((u) => changed === null || changed.has(u.id) || changed.has(u.pathId));
    if (hit) {
      throw new Refusal(
        'guard_mismatch',
        changed === null
          ? `${input.file} is at version ${doc.version}; your read (version ${input.ifVersion}) is too old to check. Re-read the units you are editing.`
          : `Unit ${hit.id} changed since version ${input.ifVersion} (now ${doc.version}). Re-read it and rebuild the edit.`,
        describeUnit(base, hit),
      );
    }
  }

  const newText = applySplices(doc.text, splices);
  const warnings: Warning[] = [];

  // 6. Per-file checks.
  if (base && !('raw' in input)) {
    const rewritten = rewrittenUnits(base, newText, splices);
    if (!input.rewrite && !isBib(input.file)) checkBudget(rewritten, threshold);
    checkReflow(rewritten);
    if (base.parse === 'fallback') {
      warnings.push(warning('parse_fallback', input.file, `${input.file} could not be parsed structurally (${base.parseError ?? 'unknown reason'}), so structural checks were limited.`));
    }
  }
  if (!('raw' in input) && !input.allowPreamble) {
    const pre = checkPreamble(doc.text, newText, input.file);
    if (pre) throw pre;
  }
  return { input: input as UpdateInput, file: input.file, tracked, baseVersion: doc.version, baseText: doc.text, newText, splices, targets, warnings };
}

/** Project-level checks over the state after every prepared edit. */
function projectChecks(session: ProjectSession, prepared: Prepared[]): { after: ProjectOutline; warnings: Warning[] } {
  const texts = new Map([...session.docs].map(([p, d]) => [p, d.text]));
  for (const p of prepared) texts.set(p.file, p.newText);
  const after = buildProjectOutline(
    [...texts].map(([path, text]) => ({ path, text })),
    session.handle.settings().rootDoc,
  );
  const edited = prepared.map((p) => p.file);
  const texEdited = edited.filter((f) => !isBib(f));
  checkLabels(session.outline, after, texEdited);
  const bibs = new Map([...texts].filter(([p]) => isBib(p)));
  return { after, warnings: checkCites(session.outline, after, texEdited, bibs) };
}

function opReceipts(p: Prepared, after: FileOutline | undefined, trackedRanges: { id: string; pos: number }[]): OpReceipt[] {
  const byOp = new Map<number, ResolvedSplice[]>();
  for (const s of p.splices) byOp.set(s.opIndex, [...(byOp.get(s.opIndex) ?? []), s]);
  const out: OpReceipt[] = [];
  const claimed = new Set<string>();
  for (const [op, sps] of [...byOp].sort((a, b) => a[0] - b[0])) {
    const units = new Map<string, string>();
    const spans: [number, number][] = [];
    for (const s of sps) {
      const ns = mapOffset(p.splices, s.start, 'left');
      const ne = ns + s.text.length;
      spans.push([ns, ne]);
      if (after) {
        const u = unitAt(after, ns, Math.max(ns, ne));
        units.set(u.id, u.hash);
        for (const x of after.units) if (x.kind !== 'section' && x.start < ne && x.end > ns) units.set(x.id, x.hash);
      }
    }
    const tc = trackedRanges.filter((r) => !claimed.has(r.id) && spans.some(([a, b]) => r.pos >= a && r.pos <= b)).map((r) => r.id);
    tc.forEach((id) => claimed.add(id));
    out.push({ op, units: [...units].map(([id, hash]) => ({ id, hash })), trackedChanges: tc });
  }
  // Any of our tracked changes we could not place go on the first op.
  const rest = trackedRanges.map((r) => r.id).filter((id) => !claimed.has(id));
  if (rest.length && out[0]) out[0].trackedChanges.push(...rest);
  return out;
}

export interface PipelineDeps {
  audit: AuditLog;
  threshold: number;
}

export async function runWrite(
  session: ProjectSession,
  edits: (UpdateInput | (RawEdit & { raw: true }))[],
  deps: PipelineDeps,
  tool: 'update' | 'batch' | 'bib',
): Promise<WriteResult> {
  await session.flush();
  const audit = (refusal: string | null, extra: Record<string, unknown> = {}) =>
    deps.audit.write({
      tool,
      projectId: session.projectId,
      file: edits.map((e) => e.file).join(','),
      ops: edits.flatMap((e) => ('raw' in e ? [{ op: 'raw', splices: e.splices.length }] : e.ops.map((o) => summarizeOp(o as unknown as Record<string, unknown>)))),
      refusal,
      ...extra,
    });
  try {
    // Steps 1–6 for every edit before anything is sent.
    const files = new Set<string>();
    const prepared = edits.map((e) => {
      if (files.has(e.file)) throw new Refusal('invalid_op', `${e.file} appears twice in the batch; put all its ops in one edit.`);
      files.add(e.file);
      return prepare(session, e, deps.threshold);
    });
    const { after, warnings: citeWarnings } = projectChecks(session, prepared);
    const warnings: Warning[] = [...prepared.flatMap((p) => p.warnings), ...citeWarnings];

    // Step 8 precondition: never fall back to untracked silently.
    if (prepared.some((p) => p.tracked) && !session.handle.settings().trackChangesAvailable) {
      throw new Refusal(
        'tracking_unavailable',
        "This project's plan or server doesn't support tracked changes, so the edit can't be sent as a tracked change. Tell the user; send untracked (\"tracked\": false) only if they explicitly agree.",
      );
    }

    // Step 7: compile gate.
    const report = await session.gate.check(new Map(prepared.map((p) => [p.file, p.newText])));
    if (report.status === 'ok' && report.fatal) {
      throw new Refusal(
        'compile_regression',
        'The edit would add LaTeX errors (or stop the PDF from building). Fix the edit; nothing was sent.',
        { newErrors: report.newErrors.map(({ key: _k, ...i }) => i), logPath: report.logPath },
      );
    }
    if (report.status === 'skipped') warnings.push(warning('compile_skipped', null, `The compile gate did not run: ${report.reason}`));
    if (report.status === 'timeout') warnings.push(warning('compile_timeout', null, `The compile gate timed out after ${session.cfg.compile.timeoutSeconds}s, so the edit was not compile-checked.`));
    for (const w of report.newWarnings) {
      warnings.push(warning('compile_warning_new', w.file, `New compile warning: ${w.message}${w.context ? ` (near "${w.context.trim().slice(0, 60)}")` : ''}.`));
    }

    // Step 8: send, in order; revert on a batch failure.
    const sent: { p: Prepared; receipt: EditReceipt }[] = [];
    for (const p of prepared) {
      const splices = p.splices.flatMap((s) => (s.rewrites ? refineSplice(p.baseText, s) : [s]));
      try {
        const receipt = await session.handle.applyEdit(p.file, { splices, baseText: p.baseText }, { baseVersion: p.baseVersion, tracked: p.tracked });
        sent.push({ p, receipt });
      } catch (err) {
        session.gate.discardPendingBaseline();
        const msg = err instanceof Error ? err.message : String(err);
        if (err instanceof BackendError && err.code === 'auth_expired') throw new Refusal('auth_expired', msg);
        if (sent.length === 0) throw new Refusal('send_failed', `Sending the edit to ${p.file} failed: ${msg}. Nothing changed; re-read and retry.`);
        const reverted: string[] = [];
        const failedReverts: string[] = [];
        for (const s of [...sent].reverse()) {
          try {
            await session.handle.revertEdit(s.p.file, s.receipt);
            reverted.push(s.p.file);
          } catch (e) {
            failedReverts.push(`${s.p.file}: ${e instanceof Error ? e.message : String(e)}`);
          }
        }
        await session.flush();
        throw new Refusal(
          'batch_partial_reverted',
          `Sending to ${p.file} failed (${msg}). Edits already sent were reverted${failedReverts.length ? ', except some that could not be — tell the user' : ''}.`,
          { failedFile: p.file, reverted, failedReverts, notSent: prepared.slice(prepared.indexOf(p) + 1).map((x) => x.file) },
        );
      }
    }

    // Step 9: post-check after our edits echo back.
    await waitForEcho(session, sent);
    await session.flush();
    session.gate.adoptPendingBaseline();
    const receipts: (OpReceipt & { file: string })[] = [];
    for (const { p, receipt } of sent) {
      const cur = session.doc(p.file);
      const fo = session.outline.files.get(p.file);
      if (cur.text !== p.newText && fo) {
        const expected = buildProjectOutline([{ path: p.file, text: p.newText }], null).files.get(p.file)!;
        const touched = new Set(p.targets.flat().map((u) => u.id));
        for (const u of expected.units) {
          if (u.kind === 'section') continue;
          const mine = p.splices.some((s) => {
            const ns = mapOffset(p.splices, s.start, 'left');
            return ns <= u.end && ns + s.text.length >= u.start;
          });
          if ((mine || touched.has(u.id)) && !cur.text.includes(p.newText.slice(u.start, u.end))) {
            warnings.push(warning('concurrent_edit', u.id, `A coauthor edited ${u.id} while this edit was being sent; both edits are in the document, but check the result reads correctly.`));
          }
        }
      }
      const ours = new Set(receipt.trackedChangeIds);
      const ranges = cur.ranges.changes.filter((c) => ours.has(c.id)).map((c) => ({ id: c.id, pos: c.pos }));
      for (const id of receipt.trackedChangeIds) if (!ranges.some((r) => r.id === id)) ranges.push({ id, pos: -1 });
      for (const r of opReceipts(p, fo, ranges)) receipts.push({ file: p.file, ...r });
    }

    // Step 10: record.
    const result: WriteResult = {
      ok: true,
      ver: session.changelog.ver,
      files: sent.map(({ p }) => ({ file: p.file, version: session.doc(p.file).version })),
      receipts,
      warnings,
    };
    void after;
    audit(null, { receipts, warnings });
    return result;
  } catch (err) {
    if (err instanceof Refusal) audit(err.code);
    else audit('internal_error', { error: err instanceof Error ? err.message : String(err) });
    throw err;
  }
}

/** Waits until the session's cached doc versions reflect our acknowledged edits. */
async function waitForEcho(session: ProjectSession, sent: { p: Prepared; receipt: EditReceipt }[]) {
  const deadline = Date.now() + 5000;
  for (;;) {
    await session.flush();
    const behind = sent.some(({ p, receipt }) => (session.docs.get(p.file)?.version ?? 0) <= receipt.appliedAt);
    if (!behind || Date.now() > deadline) return;
    await new Promise((r) => setTimeout(r, 50));
  }
}
